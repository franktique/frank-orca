// Pure TestRun -> report.md. Format: specs/003-e2e-test-orchestrator/contracts/evidence-bundle-format.md
import {
  escapeTableCell,
  formatDuration,
  formatLocalTimestamp,
  inlineCode
} from './evidence-markdown-text'
import { renderPhaseSections, renderSummaryTable } from './evidence-markdown-steps'
import type { RunDatabaseMode, TestRun } from './test-orchestrator-types'

export type EvidenceReportContext = {
  planName: string
  orcaVersion: string
  /** Minutes east of UTC for the start time label. */
  utcOffsetMinutes: number
  guideLink?: { text: string; href: string }
}

function describeDatabaseMode(mode: RunDatabaseMode): string {
  switch (mode.mode) {
    case 'automatic':
      return `Automatic — connection "${mode.connectionName}"`
    case 'browser':
      return `Browser — console at ${inlineCode(mode.site)}`
    case 'manual':
      return 'Manual'
    case 'none':
      return 'Not used'
  }
}

function describeOutcome(run: TestRun): string {
  if (run.ending === null) {
    return '⏳ Run in progress'
  }
  switch (run.ending) {
    case 'passed':
      return '✅ Passed'
    case 'failed': {
      const failed = run.steps.filter((step) => step.result === 'fail').length
      return `❌ Failed (${failed} of ${run.steps.length} steps)`
    }
    case 'stopped-by-user':
      return '⏹ Stopped by user'
    case 'preflight-failed':
      return '⚠ Preflight failed'
    case 'error':
      return '⚠ Run error'
  }
}

function describeDuration(run: TestRun): string {
  if (run.endedAt === null) {
    return '—'
  }
  const total = formatDuration(run.endedAt - run.startedAt)
  return run.pausedMs > 0 ? `${total} (paused ${formatDuration(run.pausedMs)})` : total
}

function renderHeaderTable(run: TestRun, context: EvidenceReportContext): string {
  const rows: [string, string][] = []
  if (context.guideLink) {
    rows.push(['Guide', `[${context.guideLink.text}](${context.guideLink.href})`])
  }
  rows.push(
    ['Target', run.targetHosts.length > 0 ? run.targetHosts.map(inlineCode).join(', ') : '—'],
    ['Started', formatLocalTimestamp(run.startedAt, context.utcOffsetMinutes)],
    ['Duration', describeDuration(run)],
    ['Database mode', describeDatabaseMode(run.databaseMode)],
    ['Outcome', describeOutcome(run)]
  )
  return [
    '| | |',
    '| --- | --- |',
    ...rows.map(([label, value]) => `| ${label} | ${escapeTableCell(value)} |`)
  ].join('\n')
}

function pluralizeValues(count: number): string {
  return `${count} ${count === 1 ? 'value' : 'values'}`
}

function renderCleanupSummary(run: TestRun): string {
  const { cleaned, notCleaned, keptByUser } = run.cleanup
  const lines = [`- Cleaned: ${pluralizeValues(cleaned)}`]
  if (keptByUser && notCleaned.length === 0) {
    lines.push('- Data kept by user')
  }
  for (const value of notCleaned) {
    const variable = inlineCode(value.variable)
    if (value.unavailable) {
      lines.push(
        `- Not cleaned: ${variable} — value unavailable (not stored: secure storage unavailable)`
      )
    } else {
      const suffix = keptByUser ? ' — Data kept by user' : ''
      lines.push(`- Not cleaned: ${variable} = ${inlineCode(value.valueMasked)}${suffix}`)
    }
  }
  return ['## Cleanup', '', ...lines].join('\n')
}

export function renderEvidenceReport(run: TestRun, context: EvidenceReportContext): string {
  const sections = [`# ${context.planName} — test run evidence`, renderHeaderTable(run, context)]
  if (run.evidence?.ignoredByGit) {
    sections.push('> ⚠ `evidencias/` is ignored by source control in this repository.')
  }
  sections.push(
    '## Summary',
    renderSummaryTable(run.steps),
    renderCleanupSummary(run),
    '---',
    ...renderPhaseSections(run.steps),
    '---',
    `<sub>Generated by Orca ${context.orcaVersion} · run ${run.id}</sub>`
  )
  return `${sections.join('\n\n')}\n`
}
